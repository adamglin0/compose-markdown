#!/usr/bin/env python3
"""Regenerates HtmlEntityTable.kt from the WHATWG named character reference list.

Usage: python3 markdown-core/scripts/generate_html_entities.py
"""
import json
import pathlib
import urllib.request

SOURCE_URL = "https://html.spec.whatwg.org/entities.json"
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / (
    "src/commonMain/kotlin/com/adamglin/compose/markdown/core/inline/HtmlEntityTable.kt"
)
CHUNK_SIZE = 12000


def main():
    with urllib.request.urlopen(SOURCE_URL) as response:
        data = json.load(response)
    entries = [
        name[1:-1] + ":" + "+".join("%X" % cp for cp in value["codepoints"])
        for name, value in sorted(data.items())
        if name.endswith(";")
    ]
    chunks, current, size = [], [], 0
    for entry in entries:
        if size + len(entry) > CHUNK_SIZE:
            chunks.append(" ".join(current))
            current, size = [], 0
        current.append(entry)
        size += len(entry) + 1
    chunks.append(" ".join(current))

    lines = [
        "// Generated by markdown-core/scripts/generate_html_entities.py from " + SOURCE_URL + ". Do not edit by hand.",
        "package com.adamglin.compose.markdown.core.inline",
        "",
        "/**",
        " * HTML5 named character references (only the `;`-terminated forms CommonMark recognizes),",
        " * encoded as space-separated `name:CODEPOINT[+CODEPOINT]` entries with hexadecimal code points.",
        " */",
        "internal val HTML_ENTITY_TABLE_CHUNKS: List<String> = listOf(",
    ]
    lines += ['    "' + chunk + '",' for chunk in chunks]
    lines.append(")")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print("wrote %d entities to %s" % (len(entries), OUTPUT))


if __name__ == "__main__":
    main()
