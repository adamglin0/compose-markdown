#!/usr/bin/env python3
"""Regenerates the vendored spec examples used by the conformance tests in commonTest.

- CommonMark 0.31.2: every example from spec.json.
- GFM: the extension examples (strikethrough, autolink, table) from cmark-gfm's test/spec.txt.

Usage: python3 markdown-core/scripts/generate_spec_examples.py
"""
import json
import pathlib
import urllib.request

COMMONMARK_URL = "https://spec.commonmark.org/0.31.2/spec.json"
GFM_URL = "https://raw.githubusercontent.com/github/cmark-gfm/0.29.0.gfm.13/test/spec.txt"
GFM_EXTENSIONS = {"strikethrough", "autolink", "table"}
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / (
    "src/commonTest/kotlin/com/adamglin/compose/markdown/core/spec"
)
FENCE = "`" * 32


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def kotlin_string(value):
    out = []
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "$":
            out.append("\\$")
        elif char == "\n":
            out.append("\\n")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append("\\u%04X" % ord(char))
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def gfm_examples():
    lines = fetch(GFM_URL).split("\n")
    examples, section, number, index = [], None, 0, 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("#"):
            section = line.lstrip("#").strip()
        if line.startswith(FENCE + " example"):
            number += 1
            extension = line[len(FENCE + " example"):].strip()
            index += 1
            markdown = []
            while lines[index] != ".":
                markdown.append(lines[index])
                index += 1
            index += 1
            html = []
            while lines[index] != FENCE:
                html.append(lines[index])
                index += 1
            if extension in GFM_EXTENSIONS:
                examples.append({
                    "example": number,
                    "section": section,
                    "markdown": "\n".join(markdown).replace("→", "\t") + "\n",
                    "html": "\n".join(html).replace("→", "\t") + "\n",
                })
        index += 1
    return examples


def write(name, property_name, origin, examples):
    by_section = {}
    for example in examples:
        by_section.setdefault(example["section"], []).append(example)
    lines = [
        "// Generated by markdown-core/scripts/generate_spec_examples.py from " + origin + ". Do not edit by hand.",
        "package com.adamglin.compose.markdown.core.spec",
        "",
        "internal val " + property_name + ": List<SpecExample> by lazy {",
        "    listOf(",
    ]
    function_names = []
    for position, section in enumerate(by_section):
        function_names.append("%sSection%d" % (property_name, position))
        lines.append("        %s()," % function_names[-1])
    lines += ["    ).flatten()", "}", ""]
    for function_name, (section, section_examples) in zip(function_names, by_section.items()):
        lines.append("private fun %s(): List<SpecExample> = listOf(" % function_name)
        for example in section_examples:
            lines.append(
                "    SpecExample(%d, %s, %s, %s),"
                % (
                    example["example"],
                    kotlin_string(section),
                    kotlin_string(example["markdown"]),
                    kotlin_string(example["html"]),
                )
            )
        lines += [")", ""]
    (OUTPUT_DIR / name).write_text("\n".join(lines))
    print("wrote %d examples to %s" % (len(examples), name))


def main():
    write("CommonMarkSpecExamples.kt", "commonMarkSpecExamples", COMMONMARK_URL, json.loads(fetch(COMMONMARK_URL)))
    write("GfmSpecExamples.kt", "gfmExtensionSpecExamples", GFM_URL, gfm_examples())


if __name__ == "__main__":
    main()
